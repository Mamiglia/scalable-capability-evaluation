"""Self-revealed identity in the judged transcripts: how often a transcript names its model or vendor.

    uv run python scripts/analyses/identity_leak.py

Scans the correct repeat-0 transcripts that the judges see (references and targets of every domain/semester task, on the
frozen train items), for the models of the roster (configs/semesters.yml) only. Only text the model wrote is scanned: assistant turns, their reasoning and their tool-call arguments.
Tool outputs, user and system turns are skipped, so repo files that happen to mention "OpenAI" do not count.

Flags per transcript:
  selfid_own    a first-person identity cue ("I am", "I'm", "developed by", ...) followed within 80 chars by the
                model's own vendor or model name, or a commit trailer naming it ("Co-Authored-By: Claude")
  selfid_other  the same cue followed by another vendor's name (e.g. a model that calls itself ChatGPT)
  mention_own   the own vendor or model name anywhere in the model's text (loose; includes false positives)
  cutoff        a knowledge-cutoff or training-date statement
  format        raw chat-template tokens left in the text (<|im_end|>, <|end|>, <|channel|>, ...); stray <think> tags
                are not counted (the reasoning block itself is shown to the judge anyway)

Pair level: share of judged (item, model pair) in analysis/judge/family_bias/verdicts.parquet with at least one flagged
side. Writes analysis/judge/identity_leak/{transcripts.csv, by_model.csv, pairs.csv, examples.md}.
"""

import re
from pathlib import Path

import pandas as pd

from capability.task import Task
from configs.domain import DomainConfig
from reference import tables

OUT = Path("analysis/judge/identity_leak")
DOMAINS = ["science", "math", "coding", "cyber"]
ROSTER = {m for models in tables.load_semesters().values() for m in models}  # configs/semesters.yml
FLAGS = ["selfid_own", "selfid_other", "mention_own", "cutoff", "format"]

# vendor -> names a transcript could use for itself. Case-sensitive: "Phi-3" yes, "phi" (the angle) no.
NAMES = {
    "openai": r"OpenAI|ChatGPT|GPT-?[345](?:\.\d)?(?:o|-turbo|-oss)?\b",
    "anthropic": r"Anthropic|Claude",
    "google": r"Gemini|Gemma|Google DeepMind|\bBard\b",
    "alibaba": r"Qwen|QwQ|Tongyi|Alibaba Cloud",
    "deepseek": r"DeepSeek|Deepseek",
    "moonshot": r"Kimi|Moonshot",
    "zhipu": r"ChatGLM|\bGLM-?\d|Zhipu|Z\.ai|智谱",
    "meta": r"\bLlama\b|\bLLaMA|Meta AI",
    "mistral": r"Mistral|Mixtral",
    "nvidia": r"Nemotron",
    "minimax": r"MiniMax|Minimax",
    "nous": r"Hermes|Nous Research",
    "microsoft": r"\bPhi-\d|WizardLM",
    "mosaic": r"\bMPT\b|MosaicML",
    "ant": r"\bLing-|Ant Group",
}
# model-name prefix -> vendor; the first matching prefix wins. Unknown vendors (union-alpha) only get cutoff/format.
VENDOR = {"claude": "anthropic", "gpt": "openai", "o3": "openai", "o4": "openai", "gemini": "google", "gemma": "google",
          "qwen": "alibaba", "deepseek": "deepseek", "kimi": "moonshot", "glm": "zhipu", "llama": "meta",
          "meta-llama": "meta", "hermes": "nous", "nous": "nous", "mistral": "mistral", "mixtral": "mistral",
          "open-mistral": "mistral", "nvidia": "nvidia", "minimax": "minimax", "phi": "microsoft",
          "wizardlm": "microsoft", "mpt": "mosaic", "ling": "ant"}

CUE = re.compile(r"\b(?:I am|I'm|I’m|my name is|I was (?:developed|created|trained|built|made)|"
                 r"(?:developed|created|trained|built|made) by)\b", re.I)
TRAILER = re.compile(r"(?:Co-Authored-By|Generated with|Generated by)[:\s]", re.I)
CUTOFF = re.compile(r"knowledge cut-?off|training (?:data|cut-?off)[^.\n]{0,30}\b(?:19|20)\d\d|"
                    r"as of my (?:last|latest)? ?(?:update|training|knowledge)", re.I)
FORMAT = re.compile(r"<\|(?:channel|message|start|end|im_start|im_end|begin_of_text|eot_id)\|>")
MESSAGE = re.compile(r"(?:^|\n\n)\[(Assistant|User|System|Tool)\]: ")
WINDOW = 80


def vendor(model: str) -> str | None:
    return next((v for k, v in VENDOR.items() if model.startswith(k)), None)


def own_text(text: str) -> str:
    """The model's own text: assistant messages only. A transcript with no role prefix is one assistant answer."""
    parts = MESSAGE.split(text)
    if len(parts) == 1:
        return text
    return "\n\n".join(body for role, body in zip(parts[1::2], parts[2::2]) if role == "Assistant")


def snippet(text: str, m: re.Match) -> str:
    return text[max(0, m.start() - 60):m.end() + 60].replace("\n", " ")


def scan(text: str, model: str) -> dict[str, str]:
    """flag -> first matching snippet, for the flags that fire."""
    text, own = own_text(text), vendor(model)
    found = {}
    names = {v: re.compile(p) for v, p in NAMES.items()}
    for cue in [*CUE.finditer(text), *TRAILER.finditer(text)]:
        after = text[cue.end():cue.end() + WINDOW].split("\n")[0]
        for v, pat in names.items():
            if pat.search(after):
                found.setdefault("selfid_own" if v == own else "selfid_other", snippet(text, cue))
    if own and (m := names[own].search(text)):
        found["mention_own"] = snippet(text, m)
    for flag, pat in (("cutoff", CUTOFF), ("format", FORMAT)):
        if m := pat.search(text):
            found[flag] = snippet(text, m)
    return found


def transcripts() -> pd.DataFrame:
    rows = []
    for name in DOMAINS:
        dom = DomainConfig.from_cli(Path(f"configs/domain/{name}.yml"))
        for sem_dir in sorted(Path("logs/judge", name).iterdir()):
            task = Task.from_semester(sem_dir.name, dom)
            for role, cohort in (("reference", task.references), ("target", task.test)):
                for model, by_item in cohort.transcripts.items():
                    if model not in ROSTER:
                        continue
                    for (bench, item), t in by_item.items():
                        hits = scan(t.text, model)
                        rows.append({"domain": name, "semester": sem_dir.name, "role": role, "model": model,
                                     "vendor": vendor(model), "bench": bench, "item": item,
                                     **{f: f in hits for f in FLAGS}, **{f"{f}_text": hits.get(f, "") for f in FLAGS}})
            print(name, sem_dir.name, len(rows), flush=True)
    return pd.DataFrame(rows)


def pairs(tr: pd.DataFrame) -> pd.DataFrame:
    """Per domain/semester: judged (item, unordered pair) and the share with >= 1 flagged side, per flag."""
    v = pd.read_parquet("analysis/judge/family_bias/verdicts.parquet")
    v[["a", "b"]] = pd.DataFrame(sorted(p) for p in zip(v.model_left, v.model_right)).to_numpy()
    v = v[v.a.isin(ROSTER) & v.b.isin(ROSTER)][["domain", "semester", "bench", "item", "a", "b"]].drop_duplicates()
    # A model can be a reference in one semester and a target in the next: its text is the same, keep one row.
    t = tr.drop_duplicates(["domain", "semester", "model", "bench", "item"]).set_index(["domain", "semester", "bench", "item", "model"])[FLAGS]
    key = ["domain", "semester", "bench", "item"]
    fa = t.reindex(pd.MultiIndex.from_frame(v[[*key, "a"]])).to_numpy()
    fb = t.reindex(pd.MultiIndex.from_frame(v[[*key, "b"]])).to_numpy()
    either = pd.DataFrame((fa == True) | (fb == True), columns=FLAGS, index=v.index)  # noqa: E712 (NaN = not scanned)
    either["any_selfid"] = either.selfid_own | either.selfid_other
    return pd.concat([v[["domain", "semester"]], either], axis=1).groupby(["domain", "semester"]).agg(
        pairs=("selfid_own", "size"), **{c: (c, "mean") for c in [*FLAGS, "any_selfid"]}).reset_index()


def examples(tr: pd.DataFrame, per_model: int = 3) -> str:
    out = []
    for flag in ["selfid_own", "selfid_other", "cutoff", "format", "mention_own"]:
        out.append(f"## {flag}\n")
        hit = tr[tr[flag]].drop_duplicates(["model", "bench", "item"])
        for model, g in hit.groupby("model"):
            out += [f"- **{model}** `{r.bench}/{r.item}`: …{getattr(r, f'{flag}_text')}…" for r in g.head(per_model).itertuples()]
        out.append("")
    return "\n".join(out)


def check():
    assert scan("[Assistant]: Hello, I am Claude, made by Anthropic.", "claude-opus-4.8").keys() >= {"selfid_own", "mention_own"}
    assert "selfid_other" in scan("I'm ChatGPT, a model trained by OpenAI.", "deepseek-v3")
    assert scan("[User]: are you Claude?\n\n[Tool]: [Tool Output (bash)]: import openai", "claude-opus-4.8") == {}
    assert "selfid_own" in scan("[Assistant]: [Tool Call: bash({'command': 'git commit -m x\\nCo-Authored-By: Claude'})]", "claude-fable-5")
    assert scan("The angle phi is 3 and GLM regression fits.", "phi-4") == {}
    assert "format" in scan("ANSWER: A<|im_end|>", "qwen-72b-chat")
    assert scan("<think>\nhmm</think> 42", "qwen3-32b") == {}  # reasoning tags are not counted


def main():
    check()
    OUT.mkdir(parents=True, exist_ok=True)
    tr = transcripts()
    tr.to_csv(OUT / "transcripts.csv", index=False)
    by_model = tr.drop_duplicates(["domain", "model", "bench", "item"]).groupby(["domain", "model"])[FLAGS].mean()
    by_model.insert(0, "n", tr.drop_duplicates(["domain", "model", "bench", "item"]).groupby(["domain", "model"]).size())
    by_model.round(4).to_csv(OUT / "by_model.csv")
    pr = pairs(tr)
    pr.round(4).to_csv(OUT / "pairs.csv", index=False)
    (OUT / "examples.md").write_text(examples(tr))
    pd.set_option("display.width", 200)
    print(by_model[(by_model[FLAGS[:2]] > 0).any(axis=1) | (by_model.cutoff > 0.02)].round(3).to_string())
    print(pr.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
